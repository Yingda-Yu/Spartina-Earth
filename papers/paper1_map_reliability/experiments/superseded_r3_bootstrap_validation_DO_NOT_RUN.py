def block_stats(arr_a, arr_b, H, W, bx_px, by_px):
    """Block inter/union — robust to non-divisible dims."""
    nbh = H // by_px
    nbw = W // bx_px
    n   = nbh * nbw
    # Only use the exact nbh*by_px rows and nbw*bx_px cols (discard tail which
    # is tiny relative to the domain; tail covers ~0% of area for large domains)
    H_use = nbh * by_px
    W_use = nbw * bx_px
    arr_a_crop = arr_a[:H_use, :W_use]
    arr_b_crop = arr_b[:H_use, :W_use]
    a_r = arr_a_crop.reshape(nbh, by_px, nbw, bx_px)
    b_r = arr_b_crop.reshape(nbh, by_px, nbw, bx_px)
    inter = (a_r & b_r).sum(axis=(1,3)).ravel()
    union = (a_r | b_r).sum(axis=(1,3)).ravel()
    return inter, union, nbh, nbw


def boot_iou(inter, union, n_boot, seed, chunk=200):
    """Chunked bootstrap to avoid OOM for large block counts."""
    rng = np.random.RandomState(seed)
    n = len(inter)
    ious = np.full(n_boot, np.nan)
    for c0 in range(0, n_boot, chunk):
        c1 = min(c0 + chunk, n_boot)
        idx = rng.randint(0, n, size=(c1 - c0, n))
        inter_b = inter[idx].sum(axis=1)
        union_b = union[idx].sum(axis=1)
        ious[c0:c1] = np.divide(inter_b, union_b,
            out=np.full(c1 - c0, np.nan), where=union_b > 0)
    return ious[~np.isnan(ious)]


def morans_i_block(block_ioi_centered, block_labels_h, block_labels_w, nbh, nbw):
    """Moran's I on a grid of block IoU residuals."""
    arr = np.zeros((nbh, nbw))
    # We need to assign block-level IoU to their grid positions
    # Labels: h_idx ∈ [0, nbh), w_idx ∈ [0, nbw)
    h_idx = block_labels_h  # 1D
    w_idx = block_labels_w  # 1D
    arr[h_idx, w_idx] = block_ioi_centered
    # Define 4-neighbour weights
    from scipy.signal import convolve2d
    kernel = np.array([[0,1,0],[1,0,1],[0,1,0]], dtype=float)
    W = convolve2d(np.ones_like(arr, dtype=float), kernel, mode="same", boundary="fill")
    W[W == 0] = np.nan
    lag = convolve2d(arr, kernel, mode="same", boundary="fill") / W
    # Only use positions where both arr and lag are defined
    mask = ~np.isnan(lag) & ~np.isnan(arr) & (W != 0)
    v = arr[mask]
    l = lag[mask]
    if len(v) < 20:
        return float("nan")
    nobs = len(v)
    S0 = np.sum(kernel) * nobs / 2  # approximate S0
    # Moran's I numerator: ΣΣ w_ij (x_i - x̄)(x_j - x̄) — already lag version
    num = np.sum(v * l)
    den = np.sum(v * v)
    I = (nobs / S0) * (num / den)
    return float(I)


